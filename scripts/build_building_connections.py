"""Rebuild the bounded, source-controlled inter-building circulation graph.
Uses current placement data through system Lua; no Python packages required.
Run from any directory. Does not modify streets, gameplay or source prototypes.
"""
from pathlib import Path
import subprocess, math, heapq
ROOT=Path(__file__).resolve().parents[1]
lines=subprocess.check_output(['lua','scripts/export_building_placements.lua'],cwd=ROOT,text=True).splitlines()
assets=[];obstacles=[]
def transform(a,u,v):
 c=round(math.cos(math.radians(a[3])));s=round(math.sin(math.radians(a[3])))
 return a[1]+c*u+s*v,a[2]-s*u+c*v
for line in lines:
 f=line.split('\t')
 if f[0]=='A':assets.append((f[1],*map(float,f[2:])))
 elif f[0]=='B':
  x,z=map(float,f[1:]);obstacles.append((x-56,z-68,x+56,z+68))
legacy_obstacles=list(obstacles)
# Main connector routes avoid detailed buildings. Short entrance leads may
# co-opt adjacent rear galleries, but must avoid all stairs and legacy interiors.
for a in assets:
 half=54 if a[0]=='Commercial' else 46
 corners=[transform(a,u,v) for u in [-half-6,half+6] for v in [-7,42]]
 obstacles.append((min(x for x,z in corners),min(z for x,z in corners),max(x for x,z in corners),max(z for x,z in corners)))
STEP=8
def clear(n):
 x,z=n[0]*STEP,n[1]*STEP
 return -668<=x<=668 and 358<=z<=1742 and not any(l<x<r and b<z<t for l,b,r,t in obstacles)
def safe_lead(a, p, n):
 g=(n[0]*STEP,n[1]*STEP)
 points=[p,(g[0],p[1]),g] if a[3] in (0,180) else [p,(p[0],g[1]),g]
 for start,end in zip(points,points[1:]):
  for k in range(41):
   x=start[0]+(end[0]-start[0])*k/40;z=start[1]+(end[1]-start[1])*k/40
   if any(l<x<r and b<z<t for l,b,r,t in legacy_obstacles+stair_obstacles):return False
 return True
stair_obstacles=[]
for a in assets:
 corners=[transform(a,u,v) for u in [-18,42] for v in [7,28]]
 stair_obstacles.append((min(x for x,z in corners)-7,min(z for x,z in corners)-7,max(x for x,z in corners)+7,max(z for x,z in corners)+7))
ports=[];snaps=[]
for a in assets:
 half=54 if a[0]=='Commercial' else 46
 # An exterior vestibule only one structural bay deep reaches the routing grid.
 x,z=transform(a,-half-15,30.5)
 options=sorted(((i,j) for i in range(round(x/STEP)-5,round(x/STEP)+6) for j in range(round(z/STEP)-5,round(z/STEP)+6) if clear((i,j)) and safe_lead(a,transform(a,-half-1,30.5),(i,j))),key=lambda n:(abs(n[0]*STEP-x)+abs(n[1]*STEP-z),n))
 assert options,('No portal',a)
 ports.append(transform(a,-half-1,30.5));snaps.append(options[0])
from hive_routing import find_route
def route(start,goal):
 return find_route(start,goal,clear)
# Nearest-neighbor tree connects the whole district; additional local links
# turn it into a mesh. Connections are not separately traversed NPC logic.
parent=list(range(len(assets)))
def root(i):
 while parent[i]!=i:i=parent[i]
 return i
pairs=sorted((abs(snaps[i][0]-snaps[j][0])+abs(snaps[i][1]-snaps[j][1]),i,j) for i in range(len(assets)) for j in range(i))
links=[];used=set()
for d,i,j in pairs:
 if root(i)!=root(j):parent[root(i)]=root(j);links.append((i,j,36.5));used.add((i,j))
# A second tier provides local alternate paths with a different elevation.
for i in range(len(assets)):
 candidates=[(d,a,b) for d,a,b in pairs if i in (a,b) and (a,b) not in used and d<=38]
 if candidates:
  _,a,b=candidates[0];links.append((a,b,52.5));used.add((a,b))
# Every opened upper portal must actually lead to another building. Isolated
# edge buildings get their nearest available link even outside the local radius.
upper_nodes={node for a,b,y in links if y==52.5 for node in (a,b)}
for i in range(len(assets)):
 if i not in upper_nodes:
  _,a,b=next((d,a,b) for d,a,b in pairs if i in (a,b) and (a,b) not in used)
  links.append((a,b,52.5));used.add((a,b));upper_nodes.update((a,b))

def simplify(points):
 out=[]
 for p in points:
  if out and p==out[-1]:continue
  if len(out)>1 and ((out[-2][0]==out[-1][0]==p[0]) or(out[-2][1]==out[-1][1]==p[1])):out.pop()
  out.append(p)
 return out
def lead(i):
 a=assets[i];p=ports[i];g=(snaps[i][0]*STEP,snaps[i][1]*STEP)
 # First leave the wall normally, then turn parallel outside the footprint.
 return [p,(g[0],p[1]),g] if a[3] in (0,180) else [p,(p[0],g[1]),g]
output=['--!strict','-- Generated by scripts/build_building_connections.py; edit source geometry then regenerate.','return {',' Buildings = {']
for a in assets:output.append('  { Name = "%s", X = %g, Z = %g, Yaw = %g },'%a)
output+=[' },',' Links = {']
for i,j,y in links:
 points=simplify(lead(i)+[(x*STEP,z*STEP) for x,z in route(snaps[i],snaps[j])]+list(reversed(lead(j))))
 widths=[];spaces=[]
 for k,(a,b) in enumerate(zip(points,points[1:])):
  # Widen only where the entire segment has space beside the anchored buildings.
  distance=50
  for l,v,r,t in obstacles:
   dx=max(l-max(a[0],b[0]),min(a[0],b[0])-r,0)
   dz=max(v-max(a[1],b[1]),min(a[1],b[1])-t,0)
   distance=min(distance,max(dx,dz))
  widths.append(min([8,12,18,10,16][(i+k)%5],max(8,2*distance+8)))
  spaces.append(['Service','Room','Covered','Balcony','Bridge'][(i+k)%5] if y==52.5 else ['Service','Room','Covered'][(i+k)%3])
 output.append('  {\n   A = %d,\n   B = %d,\n   Y = %g,\n   Widths = {%s}, Spaces = {%s},\n   Points = {\n%s\n   },\n  },'%(i+1,j+1,y,','.join(map(str,widths)),','.join('\"'+v+'\"' for v in spaces),'\n'.join('   {%g, %g},'%p for p in points)))
output+=[' },','}']
(ROOT/'src/server/Development/LowerLayer/BuildingConnections.luau').write_text('\n'.join(output)+'\n')
print(f'{len(assets)} buildings; {len(links)} connections; {len(links)-len(assets)+1} independent graph cycles')
