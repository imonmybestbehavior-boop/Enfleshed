"""Validate generated VFX assets and write the Luau asset manifest.

Run (plain Python 3, no numpy needed):  python3 tools/vfx_pipeline/build_manifest.py

Inputs
  assets/vfx/textures/textures.json   written by gen_textures.py
  assets/vfx/meshes/meshes.json       written by gen_meshes.py
  assets/vfx/asset_ids.json           filled in by YOU after uploading (see docs/spell-vfx-assets.md):
                                      { "flame_tongue": 1234567890, "mesh:fire_core": 2345678901 }
                                      Plain names are texture (image) ids; "mesh:<name>" keys are mesh
                                      ids. Some names exist as both a texture and a mesh.
Output
  src/shared/SpellVFXSystem/Assets/VFXAssetManifest.luau

No ID is ever invented: an entry has an Id only if asset_ids.json supplies a positive integer.
Exits non-zero if any generated file is missing or malformed.
"""
import json
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VFX = ROOT / "assets" / "vfx"
OUT = ROOT / "src" / "shared" / "SpellVFXSystem" / "Assets" / "VFXAssetManifest.luau"
FLIPBOOK_FRAMES = {"Grid2x2": 2, "Grid4x4": 4, "Grid8x8": 8}
BUILTIN_TEXTURES = {"Fire", "Smoke", "Sparkle"}
FALLBACK_SHAPES = {"Ball", "Block", "Cylinder", "Wedge"}


def check_png(path, meta, errors):
    data = path.read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        errors.append(f"{path.name}: not a PNG")
        return
    w, h, depth, ctype = struct.unpack(">IIBB", data[16:26])
    if (w, h) != (meta["width"], meta["height"]):
        errors.append(f"{path.name}: size {w}x{h} != metadata {meta['width']}x{meta['height']}")
    if depth != 8 or ctype != 6:
        errors.append(f"{path.name}: expected 8-bit RGBA, got depth {depth} type {ctype}")
    if max(w, h) > 1024:
        errors.append(f"{path.name}: Roblox downsamples textures above 1024 px")
    layout = meta.get("layout")
    if layout:
        n = FLIPBOOK_FRAMES.get(layout)
        if n is None:
            errors.append(f"{path.name}: unknown flipbook layout {layout}")
        elif w != h or w % n:
            errors.append(f"{path.name}: flipbook atlas must be square and divisible by {n}")
    if meta["fallback"] not in BUILTIN_TEXTURES:
        errors.append(f"{path.name}: fallback must be a built-in texture")


def check_mesh(name, meta, errors):
    for key in ("fbx", "glb"):
        path = VFX / "meshes" / meta[key]
        if not path.exists() or path.stat().st_size < 64:
            errors.append(f"{name}: missing {meta[key]}")
            continue
        head = path.read_bytes()[:23]
        if key == "glb" and head[:4] != b"glTF":
            errors.append(f"{name}: {meta[key]} is not binary glTF")
        if key == "fbx" and not head.startswith(b"Kaydara FBX Binary"):
            errors.append(f"{name}: {meta[key]} is not binary FBX")
    if not 0 < meta["triangles"] <= 20000:
        errors.append(f"{name}: triangle count {meta['triangles']} outside Roblox MeshPart limits")
    if meta["fallback"] not in FALLBACK_SHAPES:
        errors.append(f"{name}: unknown fallback shape {meta['fallback']}")


def lua_string(value):
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    errors = []
    textures = json.loads((VFX / "textures" / "textures.json").read_text())
    meshes = json.loads((VFX / "meshes" / "meshes.json").read_text())
    ids_path = VFX / "asset_ids.json"
    ids = json.loads(ids_path.read_text()) if ids_path.exists() else {}
    ids = {k: v for k, v in ids.items() if not k.startswith("_")}
    for name, meta in textures.items():
        check_png(VFX / "textures" / meta["file"], meta, errors)
    for name, meta in meshes.items():
        check_mesh(name, meta, errors)
    known = set(textures) | {"mesh:" + m for m in meshes}
    for name, value in ids.items():
        if name not in known:
            errors.append(f"asset_ids.json: unknown asset {name}")
        elif not (type(value) is int and value > 0):
            errors.append(f"asset_ids.json: {name} must be a positive integer asset id")
    if errors:
        print("\n".join("ERROR " + e for e in errors))
        sys.exit(1)

    def id_line(key):
        return f'"rbxassetid://{ids[key]}"' if key in ids else "nil"

    lines = [
        "--!strict",
        "-- GENERATED by tools/vfx_pipeline/build_manifest.py. Do not edit by hand.",
        "-- Ids come only from assets/vfx/asset_ids.json after you upload the files; nil means",
        "-- \"not uploaded yet\" and VFXAssets falls back to the built-in texture / primitive shape.",
        "return table.freeze({",
        "\tTextures = table.freeze({",
    ]
    for name in sorted(textures):
        m = textures[name]
        lines.append(
            f"\t\t{name} = table.freeze({{ Id = {id_line(name)}, Fallback = {lua_string(m['fallback'])}, "
            f"Flipbook = {lua_string(m['layout']) if m['layout'] else 'nil'}, Tiles = {str(m['tiles']).lower()}, "
            f"Size = Vector2.new({m['width']}, {m['height']}), Source = {lua_string('assets/vfx/textures/' + m['file'])} }}),"
        )
    lines.append("\t}),")
    lines.append("\tMeshes = table.freeze({")
    for name in sorted(meshes):
        m = meshes[name]
        x, y, z = m["size"]
        lines.append(
            f"\t\t{name} = table.freeze({{ Id = {id_line('mesh:' + name)}, Fallback = {lua_string(m['fallback'])}, "
            f"Size = Vector3.new({x}, {y}, {z}), Triangles = {m['triangles']}, "
            f"Source = {lua_string('assets/vfx/meshes/' + m['fbx'])} }}),"
        )
    lines.append("\t}),")
    lines.append("})")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    uploaded = sum(1 for n in known if n in ids)
    print(f"[vfx] manifest: {len(textures)} textures, {len(meshes)} meshes, {uploaded} with uploaded ids -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
